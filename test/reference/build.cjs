// Regenerates vectors.json from dt_ref.cpp with g++, and src/luts.ts, the
// gamut LUTs the extension ships, from the same run. The committed files are
// what the tests and the bundle read, so a machine without a compiler still
// runs the suite; run this after touching the C++.
"use strict";

const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");

const dir = __dirname;
const build = path.join(dir, ".build");
fs.mkdirSync(build, { recursive: true });
const exe = path.join(build, process.platform === "win32" ? "dt_ref.exe" : "dt_ref");

const cc = spawnSync("g++", ["-O2", "-std=c++17", "-ffp-contract=off", "-msse2", path.join(dir, "dt_ref.cpp"), "-o", exe], {
  stdio: "inherit",
});
if (cc.error || cc.status !== 0) {
  console.error("g++ is required to regenerate vectors.json (the committed file still serves the tests)");
  process.exit(2);
}

const run = spawnSync(exe, [], { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });
if (run.status !== 0) {
  console.error(run.stderr);
  process.exit(run.status ?? 1);
}
const vectors = JSON.parse(run.stdout);
fs.writeFileSync(path.join(dir, "vectors.json"), run.stdout);
console.log(`wrote ${path.join(dir, "vectors.json")} (${run.stdout.length} bytes)`);

// %.9g round-trips a float, and a JS number prints it back the same way.
const rows = (lut) => {
  const out = [];
  for (let i = 0; i < lut.length; i += 8) out.push(`  ${lut.slice(i, i + 8).join(", ")},`);
  return out.join("\n");
};
const luts = `// Generated by test/reference/build.cjs from darktable's own code
// (dt_ref.cpp): the gamut LUTs color balance rgb builds for its linear
// Rec.2020 working profile, 512 entries over the hue angle from -pi. Don't
// edit; regenerate.

/** JzAzBz: the largest chroma / lightness ratio in gamut, by JzAzBz hue. */
export const LUT_JZAZBZ: readonly number[] = [
${rows(vectors.lutJzazbz)}
];

/** darktable UCS 22: the gamut boundary's colourfulness squared (M²), by UCS hue. */
export const LUT_UCS: readonly number[] = [
${rows(vectors.lutUcs)}
];
`;
const lutsFile = path.join(dir, "..", "..", "src", "luts.ts");
fs.writeFileSync(lutsFile, luts);
console.log(`wrote ${lutsFile}`);
